import { act, fireEvent, render, screen } from '@testing-library/react'
import { afterEach, describe, expect, it, vi } from 'vitest'
import { BusinessSitePhotoCarousel } from './BusinessSitePhotoCarousel'

const images = [{ src: '/first.jpg', alt: 'First photo' }, { src: '/second.jpg', alt: 'Second photo' }, { src: '/third.jpg', alt: 'Third photo' }]
const active = (container: HTMLElement) => container.querySelector('[data-active="true"] img')?.getAttribute('alt')
afterEach(() => { vi.useRealTimers(); vi.unstubAllGlobals() })

describe('BusinessSitePhotoCarousel', () => {
  it('renders the trimmed active figure caption below the photo and above its controls', () => {
    const captioned = images.map((image, index) => ({ ...image, caption: ` Photo caption ${index + 1} ` }))
    const { container } = render(<BusinessSitePhotoCarousel images={captioned} as="figure" intervalMs={0} />)
    const caption = container.querySelector('figcaption')
    expect(caption).toHaveTextContent('Photo caption 1')
    expect(caption?.textContent).toBe('Photo caption 1')
    expect(caption?.parentElement?.tagName).toBe('FIGURE')
    expect(caption?.parentElement?.lastElementChild).toBe(caption)
    expect(container.querySelectorAll('.pz-photo-gallery__caption')).toHaveLength(1)
    expect(screen.queryByText('Photo caption 2')).toBeNull()
    fireEvent.click(screen.getByRole('button', { name: 'Next photo' }))
    expect(container.querySelector('figcaption')).toHaveTextContent('Photo caption 2')
    fireEvent.click(screen.getByRole('button', { name: 'Photo 3 of 3' }))
    expect(container.querySelector('figcaption')).toHaveTextContent('Photo caption 3')
    fireEvent.keyDown(screen.getByRole('region'), { key: 'Home' })
    expect(container.querySelector('figcaption')).toHaveTextContent('Photo caption 1')
  })
  it('keeps the caption synchronized through autoplay and the trailing clone', () => {
    vi.useFakeTimers()
    const captioned = images.slice(0, 2).map((image, index) => ({ ...image, caption: `Caption ${index + 1}` }))
    const { container } = render(<BusinessSitePhotoCarousel images={captioned} autoPlay intervalMs={2000} />)
    expect(container.querySelector('.pz-photo-gallery__caption')).toHaveTextContent('Caption 1')
    act(() => vi.advanceTimersByTime(2000))
    expect(active(container)).toBe('Second photo')
    expect(container.querySelector('.pz-photo-gallery__caption')).toHaveTextContent('Caption 2')
    act(() => vi.advanceTimersByTime(2000))
    expect(container.querySelectorAll('.pz-photo-gallery__caption')).toHaveLength(1)
    fireEvent.transitionEnd(container.querySelector('.pz-photo-gallery__track')!, { propertyName: 'transform' })
    expect(active(container)).toBe('First photo')
    expect(container.querySelector('.pz-photo-gallery__caption')).toHaveTextContent('Caption 1')
  })
  it.each([undefined, '', '   '])('omits the caption block for a missing or blank caption: %j', caption => {
    const { container } = render(<BusinessSitePhotoCarousel images={[{ ...images[0]!, caption }]} as="figure" />)
    expect(screen.getByAltText('First photo')).toBeInTheDocument()
    expect(container.querySelector('.pz-photo-gallery__caption')).toBeNull()
    expect(container.querySelector('figcaption')).toBeNull()
  })
  it('clears the previous caption when navigating to an uncaptioned photo', () => {
    const { container } = render(<BusinessSitePhotoCarousel images={[{ ...images[0]!, caption: 'First caption' }, images[1]!]} intervalMs={0} />)
    expect(container.querySelector('.pz-photo-gallery__caption')).toHaveTextContent('First caption')
    fireEvent.click(screen.getByRole('button', { name: 'Next photo' }))
    expect(active(container)).toBe('Second photo')
    expect(container.querySelector('.pz-photo-gallery__caption')).toBeNull()
    fireEvent.click(screen.getByRole('button', { name: 'Previous photo' }))
    expect(container.querySelector('.pz-photo-gallery__caption')).toHaveTextContent('First caption')
  })
  it('uses a paragraph for a div gallery and treats caption markup as plain text', () => {
    const captionText = '<strong>Installed filter</strong> & "ready"'
    const { container } = render(<BusinessSitePhotoCarousel images={[{ ...images[0]!, caption: ` ${captionText} ` }]} />)
    const caption = container.querySelector('.pz-photo-gallery__caption')
    expect(caption?.tagName).toBe('P')
    expect(caption?.textContent).toBe(captionText)
    expect(caption?.querySelector('strong')).toBeNull()
    expect(container.querySelector('figcaption')).toBeNull()
  })
  it('allows hero galleries to opt out of captions without hiding the photos or controls', () => {
    const { container } = render(<BusinessSitePhotoCarousel images={images.map(image => ({ ...image, caption: 'Hidden caption' }))} showCaptions={false} />)
    expect(container.querySelector('.pz-photo-gallery__caption')).toBeNull()
    expect(screen.queryByText('Hidden caption')).toBeNull()
    expect(screen.getByAltText('First photo')).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Next photo' })).toBeInTheDocument()
  })
  it('updates the caption after image failure and removes the gallery when every image fails', () => {
    const captioned = images.slice(0, 2).map((image, index) => ({ ...image, caption: `Caption ${index + 1}` }))
    const { container } = render(<BusinessSitePhotoCarousel images={captioned} as="figure" intervalMs={0} />)
    fireEvent.click(screen.getByRole('button', { name: 'Next photo' }))
    expect(container.querySelector('figcaption')).toHaveTextContent('Caption 2')
    fireEvent.error(screen.getByAltText('Second photo'))
    expect(active(container)).toBe('First photo')
    expect(container.querySelector('figcaption')).toHaveTextContent('Caption 1')
    expect(screen.queryByRole('button')).toBeNull()
    fireEvent.error(screen.getByAltText('First photo'))
    expect(container.innerHTML).toBe('')
  })
  it('starts article galleries paused with indicators below the photos and explicit playback', () => {
    vi.useFakeTimers()
    const { container } = render(<BusinessSitePhotoCarousel images={images} />)
    expect(container.querySelectorAll('.pz-photo-gallery__slide:not([data-clone])')).toHaveLength(3)
    expect(screen.getByRole('button', { name: 'Play slideshow' })).toBeInTheDocument()
    act(() => vi.advanceTimersByTime(30000))
    expect(active(container)).toBe('First photo')
    fireEvent.click(screen.getByRole('button', { name: 'Play slideshow' }))
    act(() => vi.advanceTimersByTime(5000))
    expect(active(container)).toBe('Second photo')
    fireEvent.click(screen.getByRole('button', { name: 'Pause slideshow' }))
    act(() => vi.advanceTimersByTime(10000))
    expect(active(container)).toBe('Second photo')
  })
  it('autoplays at the supplied interval, supports a smooth trailing clone and settles without sweeping backwards', () => {
    vi.useFakeTimers()
    const { container } = render(<BusinessSitePhotoCarousel images={images.slice(0, 2)} intervalMs={2000} autoPlay />)
    act(() => vi.advanceTimersByTime(2000))
    expect(active(container)).toBe('Second photo')
    act(() => vi.advanceTimersByTime(2000))
    expect(container.querySelector('.pz-photo-gallery__track')).toHaveStyle('--pz-photo-position: 2')
    fireEvent.transitionEnd(container.querySelector('.pz-photo-gallery__track')!, { propertyName: 'transform' })
    act(() => vi.advanceTimersByTime(650))
    expect(active(container)).toBe('First photo')
    expect(container.querySelector('[data-clone] img')).toHaveAttribute('alt', '')
  })
  it('pauses on photo hover and keyboard focus, then resumes without overriding an explicit pause', () => {
    vi.useFakeTimers()
    const { container } = render(<BusinessSitePhotoCarousel images={images} intervalMs={2000} autoPlay />)
    const viewport = screen.getByRole('region', { name: 'Photos' })
    fireEvent.mouseEnter(viewport)
    act(() => vi.advanceTimersByTime(4000))
    expect(active(container)).toBe('First photo')
    fireEvent.mouseLeave(viewport)
    fireEvent.focus(screen.getByRole('button', { name: 'Photo 1 of 3' }))
    act(() => vi.advanceTimersByTime(4000))
    expect(active(container)).toBe('First photo')
    fireEvent.blur(screen.getByRole('button', { name: 'Photo 1 of 3' }), { relatedTarget: null })
    act(() => vi.advanceTimersByTime(2000))
    expect(active(container)).toBe('Second photo')
  })
  it('keeps manual navigation bounded and supports Home, End, indicators and horizontal swipes', () => {
    const { container } = render(<BusinessSitePhotoCarousel images={images} intervalMs={0} />)
    const viewport = screen.getByRole('region')
    fireEvent.keyDown(viewport, { key: 'ArrowLeft' })
    expect(active(container)).toBe('First photo')
    fireEvent.keyDown(viewport, { key: 'End' })
    fireEvent.keyDown(viewport, { key: 'ArrowRight' })
    expect(active(container)).toBe('Third photo')
    fireEvent.click(screen.getByRole('button', { name: 'Photo 1 of 3' }))
    fireEvent.touchStart(viewport, { touches: [{ clientX: 200, clientY: 100 }] })
    fireEvent.touchEnd(viewport, { changedTouches: [{ clientX: 100, clientY: 110 }] })
    expect(active(container)).toBe('Second photo')
    fireEvent.keyDown(viewport, { key: 'Home' })
    expect(active(container)).toBe('First photo')
  })
  it('respects reduced motion, allows manual selection, and removes failed photos without an empty frame', () => {
    vi.useFakeTimers()
    vi.stubGlobal('matchMedia', () => ({ matches: true, addEventListener: vi.fn(), removeEventListener: vi.fn() }))
    const { container } = render(<BusinessSitePhotoCarousel images={images.slice(0, 2)} autoPlay />)
    expect(screen.queryByRole('button', { name: 'Pause slideshow' })).toBeNull()
    act(() => vi.advanceTimersByTime(10000))
    expect(active(container)).toBe('First photo')
    fireEvent.click(screen.getByRole('button', { name: 'Photo 2 of 2' }))
    fireEvent.error(screen.getByAltText('Second photo'))
    expect(screen.queryByRole('region')).toBeNull()
    fireEvent.error(screen.getByAltText('First photo'))
    expect(container.innerHTML).toBe('')
  })
})
